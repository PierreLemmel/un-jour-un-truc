function l(...points: number[]): number[] {
    return [...points];
}

function fromLine(points: number[]): [number, number][] {
    const result: [number, number][] = new Array(points.length);
    for (let i = 0; i < points.length - 1; i++) {
        result[i] = [points[i], points[(i + 1)]];
    }
    result[points.length - 1] = [points[points.length - 1], points[0]];
    return result;
}

function fromLines(...points: number[][]): [number, number][] {
    return points.map(fromLine).flat();
}