function fromShapes(...shapes: Shape[]): [number, number, number][] {
    return shapes.map(fromShape).flat();
}

type QuadShape = {
    type: 'quad';
    a: number;
    b: number;
    c: number;
    d: number;
}
type TriangleShape = {
    type: 'triangle';
    a: number;
    b: number;
    c: number;
}
type OvoidShape = {
    type: 'ovoid';
    center: number;
    points: number[];
}

type Shape = QuadShape | TriangleShape | OvoidShape;

function fromShape(shape: Shape): [number, number, number][] {
    switch (shape.type) {
        case 'quad':
            {
                const { a, b, c, d } = shape;
                return [
                    [a, b, d],
                    [c, d, b],
                ];
            }
        case 'triangle':
            {
                const { a, b, c } = shape;
                return [
                    [a, b, c],
                ];
            }
        case 'ovoid':
            {
                const { center, points } = shape;
                
                const result: [number, number, number][] = new Array(points.length);

                for (let i = 0; i < points.length - 1; i++) {
                    const p1 = points[i];
                    const p2 = points[(i + 1)];
                    result.push([center, p1, p2]);
                }

                result.push([center, points[points.length - 1], points[0]]);

                return result;
            }
    }
}

function q(a: number, b: number, c: number, d: number): QuadShape {
    return {
        type: 'quad',
        a,
        b,
        c,
        d,
    };
}

function t(a: number, b: number, c: number): TriangleShape {
    return {
        type: 'triangle',
        a,
        b,
        c,
    };
}

function o(center: number, points: number[]): OvoidShape {
    return {
        type: 'ovoid',
        center,
        points,
    };
}